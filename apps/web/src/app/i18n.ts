export type TranslationKey = keyof typeof translations.en;
export function t(locale: Locale, key: TranslationKey): string { return (translations[locale] ?? translations.en)[key]; }
export function formatTranslation(locale: Locale, key: TranslationKey, values: Record<string, string | number>): string {
  return Object.entries(values).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), t(locale, key));
}

